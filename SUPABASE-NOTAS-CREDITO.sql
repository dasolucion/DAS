-- 1) Correlativo propio para las NC (igual que ult_fact para facturas)
ALTER TABLE public.datos ADD COLUMN IF NOT EXISTS ult_nc text;
UPDATE public.datos SET ult_nc = '000000' WHERE ult_nc IS NULL;

-- 2) Cabecera de notas de crédito
CREATE TABLE IF NOT EXISTS public.notas_credito (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id bigint,
    cliente_id bigint,
    numero_documento text NOT NULL,
    numero_control text,
    serie text DEFAULT '',
    tipo text DEFAULT 'total',
    motivo text,
    fecha date NOT NULL DEFAULT CURRENT_DATE,
    hora text,
    base_gravada numeric(12,2) DEFAULT 0,
    monto_exento numeric(12,2) DEFAULT 0,
    iva numeric(12,2) DEFAULT 0,
    total numeric(12,2) DEFAULT 0,
    tasa numeric(12,4) DEFAULT 1,
    factura_afectada text,
    serie_factura_afectada text,
    fecha_factura_afectada text,
    monto_factura_afectada numeric(12,2),
    tfhka_estado text,
    tfhka_control text,
    tfhka_url text,
    tfhka_respuesta jsonb,
    correo_enviado boolean DEFAULT false,
    created_at timestamptz DEFAULT now()
);

-- 3) Ítems acreditados
CREATE TABLE IF NOT EXISTS public.nota_credito_detalles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_credito_id bigint NOT NULL REFERENCES public.notas_credito(id) ON DELETE CASCADE,
    producto_id bigint,
    descripcion text,
    cantidad numeric(12,2),
    precio_unitario numeric(12,2),
    codigo_impuesto text,
    tasa_iva numeric(6,2),
    valor_iva numeric(12,2),
    valor_total_item numeric(12,2)
);

CREATE INDEX IF NOT EXISTS idx_notas_credito_venta ON public.notas_credito(venta_id);
CREATE INDEX IF NOT EXISTS idx_nc_detalles_nc ON public.nota_credito_detalles(nota_credito_id);

-- 4) Seguridad (mismo modelo que el resto del sistema: la app usa la anon key)
ALTER TABLE public.notas_credito ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nota_credito_detalles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "nc_all_anon" ON public.notas_credito;
CREATE POLICY "nc_all_anon" ON public.notas_credito
    FOR ALL TO anon, authenticated, service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "ncd_all_anon" ON public.nota_credito_detalles;
CREATE POLICY "ncd_all_anon" ON public.nota_credito_detalles
    FOR ALL TO anon, authenticated, service_role USING (true) WITH CHECK (true);

-- 5) Verificación
SELECT 'ult_nc' AS concepto, ult_nc AS valor FROM public.datos ORDER BY id DESC LIMIT 1;
SELECT count(*) AS tablas_nc FROM information_schema.tables
 WHERE table_schema = 'public' AND table_name IN ('notas_credito', 'nota_credito_detalles');
